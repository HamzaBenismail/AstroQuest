// F4: deterministic offline transform. Ships no unapproved interpretation of DONKI events.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import config from '../src/data/config.json' with { type: 'json' };
import { EVENT_TYPES, buildMission, missionDates } from './donki-utils.js';

const root = resolve(import.meta.dirname, '..');
const rawDir = join(root, 'scripts/raw');
const review = process.argv.includes('--review');

async function json(path) {
  return JSON.parse(await readFile(path, 'utf8'));
}

async function main() {
  const manifest = await json(join(rawDir, 'manifest.json'));
  const dates = missionDates(manifest.window?.start, config.missionLengthDays);
  if (manifest.window?.end !== dates.at(-1)) throw new Error('Raw manifest date range does not match mission length');
  if (!review && config.stormMapping?.status !== 'approved') {
    throw new Error('Storm-level mapping is unapproved. Run `npm run clean -- --review` to inspect a draft; ask team to approve mapping and append decision to CLAUDE.md §15 before shipping.');
  }
  const datasets = {};
  for (const type of EVENT_TYPES) {
    const meta = manifest.endpoints?.[type];
    // Restrict to filenames generated by our own prefetch command.
    const requiredName = `${dates[0]}_${dates.at(-1)}-${type}.json`;
    if (meta?.file !== requiredName) throw new Error(`Missing valid ${type} raw manifest entry`);
    datasets[type] = await json(join(rawDir, requiredName));
    if (!Array.isArray(datasets[type]) || datasets[type].length !== meta.count) {
      throw new Error(`${type} raw record count differs from manifest`);
    }
  }
  const mission = buildMission({
    datasets, dates, config, mapping: config.stormMapping,
    missionId: `storm-window-${dates[0]}`,
    title: 'Ten Days at the Lunar Outpost',
  });
  const folder = review ? join(root, 'scripts/review') : join(root, 'src/data/missions');
  await mkdir(folder, { recursive: true });
  const file = join(folder, `${mission.missionId}.json`);
  await writeFile(file, `${JSON.stringify(mission, null, 2)}\n`, 'utf8');
  process.stdout.write(`${review ? 'DRAFT ONLY (NOT APPROVED)' : 'Validated mission'}: ${file}\n`);
  process.stdout.write(`Days: ${mission.days.length}; event records: ${mission.days.reduce((n, d) => n + d.events.length, 0)}; mapped storm days: ${mission.days.filter(d => d.stormLevel > 0).length}\n`);
  if (review) process.stdout.write('Inspect event IDs/labels against scripts/raw and obtain team approval before generating a shipping mission.\n');
}

main().catch(error => { process.stderr.write(`Clean failed: ${error.message}\n`); process.exitCode = 1; });
