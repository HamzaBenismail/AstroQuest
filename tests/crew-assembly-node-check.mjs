import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createCrewCandidates, createCrewRoster, selectCrewCandidate, placeCrew,
  MAX_CREW_PER_MISSION, ROOM_IDS, reconcilePlanWithCrew, checkCrewStaffing} from '../src/logic/v4/crewRules.js';
import {ROOM_ACCENTS,CREW_SUIT_COLORS,CREW_COLOR_NAMES} from '../src/ui/v4/crewColors.js';
import {roomTapAction} from '../src/ui/v4/crewTap.js';
const candidates=createCrewCandidates({candidateNames:['Ari','Juno','Rhea','Sol','Kai','Milo']});
assert.equal(MAX_CREW_PER_MISSION,6);
assert.equal(createCrewRoster({crewCount:6,crewNames:candidates.map(c=>c.name)}).length,6);
assert.equal(candidates.length,6);
assert.equal(new Set(candidates.map(c=>c.specialty)).size,6);
assert.deepEqual(new Set(candidates.map(c=>c.specialty)),new Set(ROOM_IDS));
assert.equal(new Set(Object.values(ROOM_ACCENTS)).size,6);
assert.equal(new Set(CREW_SUIT_COLORS).size,6);
assert.equal(new Set(Object.values(CREW_COLOR_NAMES)).size,6);
assert.deepEqual(candidates.map(c=>CREW_SUIT_COLORS[c.suit]),candidates.map(c=>ROOM_ACCENTS[c.specialty]));
const snapshot=JSON.stringify(candidates);
let crew=candidates.slice(0,5).map(c=>({...c}));
const result=selectCrewCandidate(crew,candidates,'crew-6',6);
assert.equal(result.ok,true);
crew=result.crew;
assert.equal(crew.length,6);
assert.ok(crew.every(c=>c.room===null));
assert.equal(selectCrewCandidate(crew,candidates,'crew-7',6).ok,false);
assert.equal(JSON.stringify(candidates),snapshot);
const place=placeCrew(crew,'crew-1','lifeSupport');
assert.equal(place.ok,true);
assert.equal(placeCrew(place.crew,'crew-2','lifeSupport').ok,false);
const plan={allocation:{lifeSupport:2,greenhouse:2,science:1,shield:1},care:false,requestAdvice:false,upgradeRoom:null,expedition:null,charge:1};
const reconciled=reconcilePlanWithCrew(plan,place.crew);
assert.deepEqual(reconciled.allocation,{lifeSupport:2,greenhouse:0,science:0,shield:0});
assert.equal(reconciled.charge,0);
assert.equal(checkCrewStaffing(place.crew,reconciled).ok,true);
assert.deepEqual(roomTapAction('lifeSupport',null,'crew-1'),{type:'FOCUS_ROOM',room:'lifeSupport'});
assert.deepEqual(roomTapAction('lifeSupport','crew-2','crew-1'),{type:'FOCUS_ROOM',room:'lifeSupport'});
assert.deepEqual(roomTapAction('lifeSupport','crew-1','crew-1'),{type:'PLACE_CREW',room:'lifeSupport'});
assert.deepEqual(roomTapAction('greenhouse','crew-1',null),{type:'PLACE_CREW',room:'greenhouse'});
const jsx=readFileSync('src/ui/v4/CrewMissionExperience.jsx','utf8');
const css=readFileSync('src/ui/v4/crew-ui.css','utf8');
const flow=readFileSync('src/ui/v4/crewFlow.js','utf8');
assert.match(jsx,/export function CrewAssembly/);
assert.match(jsx,/Pick up to \{limit\} astronauts/);
assert.match(jsx,/\.map\(candidate=>\{/);
assert.match(jsx,/\.map\(member=><div className="crew-assembly__chosen"/);
assert.doesNotMatch(jsx.slice(jsx.indexOf('export function CrewAssembly'),jsx.indexOf('function CrewToken(')),/data-drop-room/);
assert.match(jsx,/<MenuStyleSwitch uiStyle=\{uiStyle\} onToggleStyle=\{onToggleStyle\}\/>/);
assert.match(jsx,/const worker = state\.crew\.find/);
assert.match(jsx,/onClick=\{event=>clickRoom\(event,room\)\}/);
assert.match(jsx,/const showingInterior = Boolean\(worker\) \|\| previewing;/);
assert.match(jsx,/data-room-color=\{ROOMS\[room\]\.color\}/);
assert.match(jsx,/Move \{worker\.name\}/);
assert.match(flow,/case 'OPEN_CREW_ASSEMBLY'/);
assert.match(flow,/case 'TOGGLE_CANDIDATE'/);
assert.match(flow,/case 'LAUNCH'/);
assert.doesNotMatch(flow,/case 'ASSIGN_SPECIALTIES'/);
assert.match(flow,/launchCrew: launchCrew.map/);
assert.match(css,/\.crew-assembly\[data-menu-style="starry"\]:before/);
assert.match(css,/\.crew-assembly\[data-menu-style="playful"\]/);
assert.match(css,/--room-accent/);
assert.match(css,/--crew-accent/);
console.log('D6 PASS: six unique colors, up to six selected, selection-only assembly, room click through worker, matching room accents, staffing and Energy refunds.');
